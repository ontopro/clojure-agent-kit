(ns harness.setup.front-door
  "The workspace's front door: the `bb.edn` `bb init` writes at the workspace's
  root, so every command a project runs is run from there - where its session is,
  and where the build works across the workspace's folders.

  THE HARNESS RUNS IN `harness/`, NOT HERE: it reads `resources/` and finds the KIT
  as the folder above its own, so the front door does not run it in the workspace.
  Each task hands on to `bb <task>` in the KIT's `harness/`, with `KIT_WORKSPACE`
  set to the workspace (every command honours it) and every argument that looks
  like a path made absolute from the workspace, so it means what was typed. The
  KIT's folder is read from `workspace.edn` when the task runs, not written here:
  the workspace may be moved and the clone renamed.

  LOOKS LIKE A PATH is narrow on purpose: the argument exists here, or it has a
  `/` and its folder exists here (a file a command will write), or it is a bare
  `.md` or `.edn` name. A model slug (`openai/gpt-6.1-sol`) or a git rev
  (`origin/main`) has a `/` and no such folder, and is handed on as typed; so is
  an absolute path.

  A TASK KEEPS ITS NAME at the front door, but for one: the workspace's gates, `workspace-gates`
  here, are `bb gates` there (`door-names`) - `gates` here is the KIT's own.

  Every harness task is in exactly one of two lists - the front door's, or the
  KIT's own development's - and a test holds the two to the harness's `bb.edn`,
  so a new command cannot miss the front door unnoticed.

  A WORKSPACE KEEPS THE FRONT DOOR IT WAS MADE WITH until `bb front-door-sync`
  writes it again from the KIT it has now: a command the KIT adds after `bb init`
  reaches the workspace only then, and `bb doctor` says when one is missing.
  The file is generated, so a project's own tasks belong in its application's
  `bb.edn`; a `bb.edn` at the root that `bb init` did not write is never
  overwritten."
  (:require
   [babashka.fs :as fs]
   [clojure.edn :as edn]
   [clojure.string :as str]
   [harness.setup.workspace :as workspace]))

(def kit-only
  "The harness tasks a project never runs from its workspace: the KIT's own gates
  and syncs, the security reviewer's fixture and its scoring, the tour, the REPL,
  and the two setup commands run from the clone before a workspace exists."
  #{"gates" "test" "fmt" "fmt-check" "lint" "repair" "inventory-sync" "health-sync"
    "bake-off-check" "security-fixture" "security-score" "security-bake-off"
    "example" "dev" "init" "health"})

(def tasks
  "The harness tasks the front door offers, by their name here (`door-name` is the one there)."
  ["next" "brief" "doctor" "plan-check" "plan-review" "blueprint-review" "spec-from-blueprint" "sigs"
   "run-loop" "stage-report" "profile" "models" "balance" "bake-off" "rules-sync" "rules-check"
   "rules-prompt" "skills-sync" "boundary" "report" "report-check" "reprice"
   "security-review" "security-route" "front-door-sync" "workspace-gates" "template-upgrade"])

(def door-names
  "A harness task the front door offers under another name: the workspace's gates are `bb gates`
  there, the name the KIT's own gates have here."
  {"workspace-gates" "gates"})

(defn door-name
  "The name the front door offers the harness task `t` under."
  [t]
  (get door-names t t))

(defn harness-tasks
  "The harness `bb.edn`'s tasks, `{name doc}`, from its text."
  [bb-edn-text]
  (into {} (for [[k v] (:tasks (edn/read-string bb-edn-text))
                 :when (symbol? k)]
             [(str k) (when (map? v) (:doc v))])))

(def ^:private header
  ";; GENERATED by `bb init` and `bb front-door-sync` - the workspace's front door. Every command a project runs is run
;; from this folder: each task below hands on to the same task in the KIT's harness/, with
;; KIT_WORKSPACE set to this folder and every argument that looks like a path made absolute
;; from here. The KIT's folder is read from workspace.edn when a task runs.
")

(def ^:private init-form
  ;; Text, not data: written once into the workspace's bb.edn, which is EDN - so no
  ;; reader macros (`#(`, `#\"`), and a regex is built from a string.
  "(do (def here (str (fs/parent (fs/absolutize (System/getProperty \"babashka.config\")))))
            (defn harness-dir []
              (let [kit (:workspace/kit (edn/read-string (slurp (str (fs/path here \"workspace.edn\")))))]
                (str (fs/normalize (fs/path here kit \"harness\")))))
            (defn path-like? [a]
              (and (not (str/starts-with? a \"-\")) (not (fs/absolute? a))
                   (or (fs/exists? (fs/path here a))
                       (and (str/includes? a \"/\") (fs/exists? (fs/parent (fs/path here a))))
                       (re-find (re-pattern \"\\\\.(md|edn)$\") a))))
            (defn kit [task args]
              (let [args (map (fn [a] (if (path-like? a) (str (fs/absolutize (fs/path here a))) a)) args)
                    {:keys [exit]} (apply shell {:dir (harness-dir) :continue true
                                                 :extra-env {\"KIT_WORKSPACE\" here}}
                                          \"bb\" task args)]
                (when-not (zero? exit) (System/exit exit)))))")

(defn render
  "The workspace's `bb.edn`: the header, then one task per name in `tasks` with
  the harness task's own doc, `docs` being `harness-tasks`'s map."
  [docs]
  (str header
       "{:tasks\n {:requires ([babashka.fs :as fs]\n             [clojure.edn :as edn]\n             [clojure.string :as str])\n"
       "  :init " init-form "\n"
       (str/join (for [t tasks]
                   (str "\n  " (door-name t) " {:doc " (pr-str (or (get docs t) (str "bb " t " in the KIT's harness/")))
                        "\n" (apply str (repeat (+ 4 (count (door-name t))) " "))
                        ":task (kit " (pr-str t) " *command-line-args*)}")))
       "}}\n"))

(def generated-mark
  "How a front door begins: a `bb.edn` at a workspace's root that does not is
  the project's own, and is never overwritten."
  ";; GENERATED by `bb init`")

(defn offered
  "The task names a front door's text offers, or nil when it does not read."
  [bb-edn-text]
  (try (into #{} (comp (filter symbol?) (map str)) (keys (:tasks (edn/read-string bb-edn-text))))
       (catch Exception _ nil)))

(defn sync!
  "The front door at `ws-dir` against what the KIT at `kit-dir` writes now:
  `{:path :existed? :generated? :changed? :missing}`, `:missing` the tasks this
  KIT offers that the front door there lacks. Written unless `check?`, or unless
  the file there is not one `bb init` wrote."
  [kit-dir ws-dir & {:keys [check?]}]
  (let [path (fs/path ws-dir "bb.edn")
        want (render (harness-tasks (slurp (str (fs/path kit-dir "harness" "bb.edn")))))
        have (when (fs/exists? path) (slurp (str path)))
        generated? (or (nil? have) (str/starts-with? have generated-mark))
        r {:path (str path) :existed? (some? have) :generated? generated? :changed? (not= want have)
           :missing (vec (remove (or (some-> have offered) #{}) (map door-name tasks)))}]
    (when (and (:changed? r) generated? (not check?))
      (spit (str path) want))
    r))

(defn -main
  "bb front-door-sync [--check] [--workspace <dir>]

  The workspace's `bb.edn` written again from this KIT's task list - run from
  the workspace folder, or for a workspace with no front door yet, in the KIT's
  `harness/` with `--workspace <dir>` (or `KIT_WORKSPACE`). `--check` only
  compares, a difference being exit 1. A `bb.edn` there that `bb init` did not
  write is refused, exit 1."
  [& args]
  (let [ws (workspace/current-or-exit args)
        {:keys [args]} (workspace/split-args args)
        check? (boolean (some #{"--check"} args))]
    (when-not ws
      (println "front-door-sync: no workspace here - run it from a workspace folder, or with --workspace <dir> in the KIT's harness/")
      (System/exit 1))
    (let [kit-dir (or (:workspace/kit ws) (str (fs/parent (fs/normalize (fs/absolutize ".")))))
          {:keys [path existed? generated? changed? missing]} (sync! kit-dir (:workspace/dir ws) :check? check?)]
      (cond
        (not generated?)
        (do (println (str "front-door-sync: " path " is not a front door bb init wrote - it is the project's own and is left as it is; "
                          "a project's own tasks belong in its application's bb.edn"))
            (System/exit 1))

        (not changed?) (println (str "front door: " path " is what this KIT writes"))

        check?
        (do (println (str "front door: " path (if existed? " differs from what this KIT writes" " is missing")
                          (when (and existed? (seq missing)) (str " - it lacks " (str/join ", " missing)))))
            (System/exit 1))

        :else (println (str "front door: wrote " path
                            (when (and existed? (seq missing)) (str " - it now offers " (str/join ", " missing)))))))))
