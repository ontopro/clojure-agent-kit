(ns harness.setup.front-door-test
  (:require
   [clojure.edn :as edn]
   [clojure.set :as set]
   [clojure.string :as str]
   [clojure.test :refer [deftest is testing]]
   [harness.setup.front-door :as front-door]))

(def harness (front-door/harness-tasks (slurp "bb.edn")))

(deftest every-harness-task-is-in-exactly-one-list
  ;; A task the harness gains must be put on the front door or named the KIT's own:
  ;; this fails until it is.
  (let [offered (set front-door/tasks)]
    (is (= (set (keys harness)) (set/union offered front-door/kit-only))
        "every harness task is offered or kit-only, and nothing else is listed")
    (is (empty? (set/intersection offered front-door/kit-only)) "no task is in both")))

(deftest the-front-door-is-edn-with-a-task-per-command
  (let [text (front-door/render harness)
        m (edn/read-string text)]
    (is (str/starts-with? text ";; GENERATED by `bb init`"))
    (is (not (str/includes? text "#(")) "bb.edn is EDN: no reader macros")
    (is (= (set (map symbol front-door/tasks)) (set (filter symbol? (keys (:tasks m))))))
    (testing "each task hands on to the same harness task, with the harness's own doc"
      (is (= "(kit \"next\" *command-line-args*)" (pr-str (:task (get-in m [:tasks 'next])))))
      (is (= (get harness "next") (:doc (get-in m [:tasks 'next])))))
    (is (str/includes? (pr-str (get-in m [:tasks :init])) "KIT_WORKSPACE"))))
